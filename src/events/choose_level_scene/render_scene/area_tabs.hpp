#pragma once
// Adventure-world buttons of the choose-level scene (PvZ Replanted reskin):
// seven sign-board buttons SCATTERED OVER THE MAP at the positions the retail
// Unity prefab pins them (P_LevelSelect.prefab ModeButtons children on the
// 4096x2160 height-matched frontend canvas, uniformly scaled here by
// k = 600/2160): DAY/NIGHT/POOL/FOG/ROOF march diagonally up the map, BONUS
// LEVELS and CLOUDY DAY stand far right as in the original. DAY..ROOF work
// like the old area tabs -- click jumps the page to the world's first level,
// the button locks below its unlock threshold; CLOUDY DAY and BONUS LEVELS
// are decorative stubs (the modes are not in this clone), always shown
// Disabled and swallowing their clicks. The sign sprites come pre-rendered
// from resources/images/replanted/ as in retail the world NAME is drawn on
// top as text (TMP Label_* children in the prefab), so a text label is drawn
// over each sign at the prefab's label anchor, and the background never
// flips with the hovered/shown world.
#include "elements/button/button.hpp"

struct AreaTab
{
    int normal_dir;   // idle sign art
    int selected_dir; // shown-page world + hover sheen (retail "Selected")
    int toggled_dir;  // pressed-pink art, kept in the set but never shown
    int disabled_dir; // locked / decorative look
    SDL_Rect box;     // where the sprite CONTENT sits (prefab placement x k)
    Button hit;       // hover/click rect: the content box inset ~8%
};

const int AREA_TAB_COUNT = 7; // DAY NIGHT POOL FOG ROOF + CLOUDY DAY + BONUS
const int AREA_TAB_AREAS = 5; // the first five are the adventure worlds
// Hit rects hug the visible sign: this many percent trimmed off each edge
// of the content box (the boxes of neighbouring signs interlock where the
// retail sprites' transparent corners overlap; see area_tabs.cpp).
const int AREA_TAB_HIT_INSET = 8;

extern const AreaTab AREA_TABS[AREA_TAB_COUNT];

// Retail stacking of the seven signs, BOTTOM to TOP, derived from the
// P_LevelSelect.prefab ModeButtons child order (LimboContent -> Pool -> Fog
// -> Roof -> Night -> Day -> Cloudy) and applied as tab indices so every
// real overlap resolves like the original: night covers pool, day covers
// night, roof covers fog, cloudy day drawn last / front-most. Clicks scan
// this order backwards (front-most first).
extern const int AREA_TAB_DRAW_ORDER[AREA_TAB_COUNT];

// World-name label of one sign: an OFFLINE-BAKED image (Dwarvesc + approved
// recipe -- idle: black fill + #9ED379 shadow 1px down + #555563 glow; hot:
// #FFDEF7 fill + black shadow (-1,-1) + #F627C4 glow; generated by
// day_decor/forensic/make_area_labels.py into resources/images/Choose_level/
// labels/) drawn centered at the prefab's label anchor (rel the sign center
// x k = 600/2160, canvas Y-up flipped). center (0,0) = no label (the Cloudy
// Day tombstone ships none). `slant` = HORIZONTAL SHEAR applied to the label
// image in window px across its full height (top edge shifts -slant/2,
// bottom +slant/2): tune độ nghiêng chữ ở AREA_LABELS bên area_tabs.cpp,
// không cần bake lại PNG (0 = phẳng, dương = nghiêng phải xuống dưới).
struct AreaLabel
{
    int cx, cy;
    int label_dir;     // idle baked label (-1 = none)
    int label_hot_dir; // hovered/selected baked label
    float slant;       // px — độ nghiêng chữ (shear ngang), 0 = phẳng
};

extern const AreaLabel AREA_LABELS[AREA_TAB_COUNT];

// Adventure areas are 10 levels wide: DAY 1-10 ... ROOF 41-50.
int area_of_level(int level_num);
int area_first_level(int area);
bool area_unlocked(int area, int unlocked_level);
// FRONT-MOST tab under the point (signs are drawn back-to-front in
// AREA_TAB_DRAW_ORDER, so the scan runs the order backwards, topmost
// first), -1 if none. Decorative stubs included.
int area_tab_at(int mouse_x, int mouse_y);
// Art the tab draws in its current state: the Disabled art when locked or
// decorative, the Selected art for the shown page's world, the Selected art
// on hover too (white sheen; Bonus ships none and stays Normal), else the
// Normal art. The pink Toggled art is the pressed state, never drawn.
int area_tab_art_dir(int tab, bool hovered);

enum AreaTabClick
{
    AREA_TAB_NONE,     // no tab under the point: keep handling the click
    AREA_TAB_DISABLED, // locked or decorative tab: swallow the click silently
    AREA_TAB_JUMPED    // page jumped to the tab's area
};

/*Apply a click on the map buttons: an enabled world button jumps shown_level
to the world's first level; a locked or decorative button swallows the click
so nothing behind it fires.*/
AreaTabClick handle_area_tab_click(int mouse_x, int mouse_y);

// Draws every sign at its measured map spot in its current state.
void display_area_tabs(const bool &is_mouse_needed);
